#!/usr/bin/env python3
"""Turn the result files of tests/compat.rs into docs/compatibility.md and the
short table in the README. Never edit either table by hand.

    scripts/compat-report.py RESULTS_DIR [--source TEXT] [--readme README.md]
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START = "<!-- compat:start (generated by scripts/compat-report.py) -->"
END = "<!-- compat:end -->"
FEATURES = {
    "browse": "Browse",
    "edit": "Edit",
    "ttl": "TTL",
    "rename": "Rename",
    "copy": "Copy",
    "type_filter": "Type filter",
    "bulk_delete": "Bulk delete",
    "live": "Live",
    "pubsub": "Pub/Sub",
    "sharded_pubsub": "Sharded Pub/Sub",
    "monitor": "MONITOR",
    "slowlog": "Slowlog",
    "streams": "Streams",
    "json": "RedisJSON",
}
MARK = {"ok": "✓", "fallback": "fallback", "failed": "✗", "n/a": "–"}


def load(results):
    rows = []
    for line in (ROOT / "tests/compat/images.txt").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        label = line.split()[0]
        path = results / f"{label}.json"
        if not path.exists():
            sys.exit(f"missing result file: {path}")
        row = json.loads(path.read_text())
        missing = set(FEATURES) - set(row["features"])
        if missing:
            sys.exit(f"{label}: no result for {sorted(missing)}")
        rows.append(row)
    return rows


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def full(rows, source):
    out = [
        "# Server compatibility",
        "",
        "Generated by `scripts/compat-report.py` from the result files of",
        "`tests/compat.rs`. Do not edit by hand.",
        "",
        f"**Source:** {source}",
        "",
        "✓ works · fallback = works another way (see the notes) · ✗ fails · – not offered by this server",
        "",
        "| Server | Version | " + " | ".join(FEATURES.values()) + " |",
        "|---|---|" + "---|" * len(FEATURES),
    ]
    for row in rows:
        marks = [MARK[row["features"][f]["status"]] for f in FEATURES]
        out.append(f"| {row['label']} | {cell(row['version'])} | " + " | ".join(marks) + " |")
    out += ["", "## Notes", ""]
    noted = False
    for row in rows:
        for feature, title in FEATURES.items():
            result = row["features"][feature]
            if result["note"]:
                noted = True
                out.append(f"- **{row['label']}, {title}:** {cell(result['note'])}")
    if not noted:
        out.append("None.")
    out += ["", "## Images", ""]
    out += [f"- `{row['label']}`: `{row['image']}`" for row in rows]
    return "\n".join(out) + "\n"


def short(rows):
    out = [START, "| Server | Works | Fallback | Fails |", "|---|---|---|---|"]
    for row in rows:
        by = lambda status: [t for f, t in FEATURES.items() if row["features"][f]["status"] == status]
        offered = len(FEATURES) - len(by("n/a"))
        out.append(
            f"| {row['label']} ({cell(row['version'])}) | {len(by('ok'))} of {offered} "
            f"| {', '.join(by('fallback')) or '–'} | {', '.join(by('failed')) or '–'} |"
        )
    out.append(END)
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("results", type=Path)
    parser.add_argument("--source", default="local run")
    parser.add_argument("--readme", type=Path)
    parser.add_argument("--out", type=Path, default=ROOT / "docs/compatibility.md")
    args = parser.parse_args()
    rows = load(args.results)
    args.out.write_text(full(rows, args.source))
    if args.readme:
        text = args.readme.read_text()
        if START not in text or END not in text:
            sys.exit(f"{args.readme}: no compat markers")
        head, rest = text.split(START, 1)
        args.readme.write_text(head + short(rows) + rest.split(END, 1)[1])


if __name__ == "__main__":
    main()
